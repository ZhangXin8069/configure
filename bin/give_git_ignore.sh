#!/usr/bin/env bash
# 依据 git 工作区现有文件的后缀生成 .gitignore：
# 仅保留这些后缀 + keep 清单，其余全部忽略。
# 若已存在 .gitignore，会先重命名为 .gitignore.<YYYY-MM-DD-HH-MM-SS>.bak
#
# 用法: gen_gitignore_from_exts.sh [-f] [-n] [-o OUT] [-k PATTERN]... [--no-default-keep]
#   -f               跳过备份，直接覆盖已存在的 .gitignore
#   -n, --dry-run    只打印，不写入、不备份
#   -o OUT           输出路径（默认 <repo>/.gitignore）
#   -k PATTERN       追加保留项（可多次）
#   --no-default-keep 丢弃内建默认 keep 清单
set -euo pipefail

# ---- 默认保留: 无后缀 / 特殊情况但值得纳入版本控制的文件 ----
DEFAULT_KEEP=(
  'Makefile' 'makefile' 'GNUmakefile'
  'Dockerfile' 'dockerfile' 'Containerfile'
  'LICENSE' 'LICENSE.*' 'COPYING' 'COPYING.*' 'NOTICE' 'NOTICE.*'
  'README' 'README.*' 'AUTHORS' 'CONTRIBUTORS'
  'CHANGELOG' 'CHANGELOG.*'
  '.gitignore' '.gitattributes' '.gitmodules' '.gitkeep'
  '.editorconfig' '.clang-format' '.clang-tidy'
  '.env.example' '.env.sample' '.keep'
)

FORCE=0; DRY=0; OUT=""; NO_DEFAULT=0
EXTRA_KEEP=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        -f|--force)           FORCE=1; shift ;;
        -n|--dry-run)         DRY=1; shift ;;
        -o|--output)          OUT="${2:?}"; shift 2 ;;
        -k|--keep)            EXTRA_KEEP+=("${2:?}"); shift 2 ;;
        --no-default-keep)    NO_DEFAULT=1; shift ;;
        -h|--help)
            sed -n '2,14p' "$0"; exit 0 ;;
        *) echo "Unknown arg: $1" >&2; exit 1 ;;
    esac
done

root=$(git rev-parse --show-toplevel 2>/dev/null) || {
    echo "Not inside a git repository." >&2; exit 1; }
cd "$root"
OUT=${OUT:-$root/.gitignore}

# ---- 备份已存在的 .gitignore ----
# 命名: <file>.<YYYY-MM-DD-HH-MM-SS>.bak；同秒冲突追加 -N
backup_existing() {
    local f="$1" ts bak i
    ts=$(date '+%Y-%m-%d-%H-%M-%S')
    bak="${f}.${ts}.bak"
    i=1
    while [[ -e "$bak" ]]; do
        bak="${f}.${ts}-${i}.bak"
        ((i++))
    done
    mv -- "$f" "$bak"
    printf '%s\n' "$bak"
}

if [[ -e "$OUT" ]]; then
    if (( FORCE == 1 )); then
        :  # 直接覆盖，不备份
    elif (( DRY == 1 )); then
        echo "[dry-run] would back up: $OUT -> ${OUT}.<ts>.bak" >&2
    else
        bak=$(backup_existing "$OUT")
        echo "backed up: $OUT -> $bak"
    fi
fi

# ---- 合并 keep 清单并去重 ----
keep=()
(( NO_DEFAULT == 0 )) && keep+=("${DEFAULT_KEEP[@]}")
(( ${#EXTRA_KEEP[@]} )) && keep+=("${EXTRA_KEEP[@]}")

declare -A _seen=()
uniq_keep=()
for p in "${keep[@]}"; do
    [[ -n "${_seen[$p]:-}" ]] && continue
    _seen[$p]=1
    uniq_keep+=("$p")
done

# ---- 收集工作区现有后缀 ----
# 注: 备份文件 <file>.<ts>.bak 若以 . 开头（默认 .gitignore 就是），
#     会被 basename 过滤规则 [[ $b != .* ]] 自动跳过，不污染白名单。
mapfile -t exts < <(
    git ls-files -co --exclude-standard -z |
    while IFS= read -r -d '' f; do
        b=${f##*/}
        [[ $b == *.* && $b != .* ]] && printf '%s\n' "${b##*.}"
    done | sort -u
)

# ---- 生成内容 ----
gen() {
    echo "# Auto-generated by $(basename "$0") at $(date '+%F %T')"
    echo "# 策略: 仅保留工作区现有后缀 + keep 清单, 其余全部忽略"
    echo
    echo "# 1) 先忽略一切"
    echo "*"
    echo "# 2) 重新包含目录, 保证 git 能递归遍历(否则 !*.ext 不生效)"
    echo "!*/"
    echo
    echo "# 3) 保留工作区现有后缀"
    if (( ${#exts[@]} == 0 )); then
        echo "# (无)"
    else
        for e in "${exts[@]}"; do
            e=${e//\\/\\\\}; e=${e//\!/\\!}; e=${e//\#/\\#}
            e=${e//\[/\\[};  e=${e//\]/\\]}
            printf '!*.%s\n' "$e"
        done
    fi
    echo
    echo "# 4) 保留无后缀 / 特殊文件 (默认清单 + 用户 -k)"
    if (( ${#uniq_keep[@]} == 0 )); then
        echo "# (无)"
    else
        for p in "${uniq_keep[@]}"; do printf '!%s\n' "$p"; done
    fi
}

if (( DRY == 1 )); then
    gen
else
    gen > "$OUT"
    echo "written: $OUT"
    echo "kept extensions (${#exts[@]}):"
    (( ${#exts[@]} )) && printf '  .%s\n' "${exts[@]}"
    echo "kept special files (${#uniq_keep[@]}):"
    (( ${#uniq_keep[@]} )) && printf '  %s\n' "${uniq_keep[@]}"
fi
